#!/usr/bin/env python3
"""Generate a child's AGENTS.md from its .claude/rules/, so agents that do
not read Claude Code's rule files (Antigravity, Codex, Cursor, ...) get the
same rules. Rules without `paths:` go in verbatim, brain-os core first, then
the child's `project.md`, then its other local rules; path-scoped rules go in
as one pointer line each. Only the brain-os sync header is dropped, so a
managed block another tool writes (e.g. `next dev`'s) survives byte for byte.

Read-only with --check. Standard library only, Python 3.8+.

    agents_md.py <child-repo> [--check] [--force]

--check  exit 1 when AGENTS.md is missing or differs from what would be
         generated; write nothing.
--force  overwrite an AGENTS.md this script did not write.
"""

import argparse
import os
import re
import sys

MARKER = "<!-- Generated by brain-ai-factory's agents_md.py from .claude/rules/."
# Antigravity truncates AGENTS.md at about 24 KB (bookete measured it,
# 2026-09-23); bookete's own budget is 20,000 bytes, kept here.
SIZE_LIMIT = 20000
CORE_ORDER = ["hard-rules.md", "principles.md"]
SYNC_HEADER = "<!-- Synced from brain-os"


def split_rule(text):
    """(paths, body) of a rule file: `paths:` from the frontmatter as a list
    (YAML list or comma-separated string), body without frontmatter and
    without the brain-os sync header."""
    paths = []
    body = text
    match = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if match:
        body = text[match.end():]
        front = match.group(1)
        inline = re.search(r"^paths:[ \t]*(\S.*)$", front, re.M)
        if inline:
            paths = [p.strip().strip("\"'") for p in inline.group(1).strip("[]").split(",")]
        else:
            paths = re.findall(r"^\s*-\s*[\"']?([^\"'\n]+?)[\"']?\s*$", front, re.M)
    body = "\n".join(line for line in body.splitlines() if not line.startswith(SYNC_HEADER))
    return [p for p in paths if p], body.strip()


def rule_files(repo):
    """Repo-relative paths of every .md under .claude/rules/: brain-os core
    files first (hard rules, principles, then the rest), then the child's
    project.md, then its other local rules."""
    root = os.path.join(repo, ".claude", "rules")
    found = []
    for directory, _, names in os.walk(root):
        for name in names:
            if name.endswith(".md"):
                found.append(os.path.relpath(os.path.join(directory, name), repo))

    def key(path):
        parts = path.split(os.sep)
        core = len(parts) > 3 and parts[2] == "brain-os"
        if core:
            rank = CORE_ORDER.index(parts[-1]) if parts[-1] in CORE_ORDER else len(CORE_ORDER)
        else:
            rank = 0 if path == os.path.join(".claude", "rules", "project.md") else 1
        return (0 if core else 1, rank, path)

    return sorted(found, key=key)


def render(repo):
    files = rule_files(repo)
    if not files:
        return None
    inline, scoped = [], []
    for rel in files:
        with open(os.path.join(repo, rel), encoding="utf-8") as handle:
            paths, body = split_rule(handle.read())
        if paths:
            globs = ", ".join(f"`{p}`" for p in paths)
            scoped.append(f"- Before you change files matching {globs}, read `{rel}`.")
        elif body:
            inline.append(body)
    parts = [MARKER + " Do not edit: change the rule files and rerun it. -->"]
    for body in inline:
        parts += ["", body]
    if scoped:
        parts += ["", "# Rules for specific files", ""] + scoped
    return "\n".join(parts) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("repo")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()

    repo = os.path.abspath(args.repo)
    text = render(repo)
    if text is None:
        print("agents_md: no .claude/rules/*.md in this repo", file=sys.stderr)
        return 2
    target = os.path.join(repo, "AGENTS.md")
    current = None
    if os.path.isfile(target):
        with open(target, encoding="utf-8") as handle:
            current = handle.read()

    if args.check:
        if current == text:
            print("AGENTS.md is up to date")
            return 0
        print("AGENTS.md is missing or stale: rerun agents_md.py", file=sys.stderr)
        return 1
    if current is not None and not current.startswith(MARKER) and not args.force:
        print("agents_md: AGENTS.md was not generated by this script; move its rules to "
              ".claude/rules/ first, or pass --force", file=sys.stderr)
        return 1
    with open(target, "w", encoding="utf-8") as handle:
        handle.write(text)
    print(f"wrote AGENTS.md ({len(text.encode('utf-8'))} bytes)")
    if len(text.encode("utf-8")) > SIZE_LIMIT:
        print(f"agents_md: over {SIZE_LIMIT} bytes, Antigravity truncates AGENTS.md near 24 KB",
              file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
